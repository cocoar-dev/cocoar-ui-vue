// Copy raw library defaults, including grouped roots and scheme-dependent colours.
// node --experimental-strip-types packages/ui/scripts/write-role-input-defaults.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { register } from 'node:module';

register(`data:text/javascript,${encodeURIComponent(`
  export async function resolve(specifier, context, next) {
    try { return await next(specifier, context); }
    catch (error) {
      if (!specifier.startsWith('.')) throw error;
      return next(specifier + '.ts', context);
    }
  }`)}`);
const { COMPACT_THEME } = await import('../src/theme/compact-theme.ts');
const { ENTERPRISE_THEME } = await import('../src/theme/enterprise-theme.ts');
const { ROLE_DERIVED_TOKENS } = await import('../src/theme/role-derived-tokens.ts');
const roles = new Set([...ROLE_DERIVED_TOKENS, ...Object.keys(ENTERPRISE_THEME.roles)]);
const inputs = new Set([COMPACT_THEME, ENTERPRISE_THEME]
  .flatMap(theme => [...Object.keys(theme.tokens), ...Object.keys(theme.mobileTokens)])
  .filter(name => !roles.has(name)));
const directory = new URL('../styles/tokens/', import.meta.url);
const imports = readFileSync(new URL('all.css', directory), 'utf8');
const skip = new Set([
  'colors-primitives-dark.css', 'typography-responsive.css',
  'theme-none.css', 'mobile.css', 'derived.css', 'compact.css',
]);
const defaults = {};
const rootRoles = {};
const schemeRoles = { light: {}, dark: {} };
const schemeInputs = { light: {}, dark: {} };
for (const [, file] of imports.matchAll(/@import '\.\/([^']+)';/g)) {
  if (skip.has(file)) continue;
  const css = readFileSync(new URL(file, directory), 'utf8');
  // Token stylesheets use flat rules. Match individual selectors, including
  // ":root, .light-mode", and retain var() expressions instead of resolved values.
  for (const [, selectors, body] of css.replace(/\/\*[\s\S]*?\*\//g, '').matchAll(/([^{}]+)\{([^{}]+)\}/g)) {
    const names = selectors.split(',').map(selector => selector.trim());
    for (const [, name, raw] of body.matchAll(/^\s*(--coar-[\w-]+):\s*([^;]+);/gm)) {
      const value = raw.trim().replace(/\s+/g, ' ');
      if (names.includes(':root')) {
        if (inputs.has(name)) defaults[name] = value;
        if (roles.has(name)) rootRoles[name] = value;
      }
      for (const scheme of ['light', 'dark']) {
        if (!names.includes(`.${scheme}-mode`)) continue;
        if (roles.has(name)) schemeRoles[scheme][name] = value;
        if (inputs.has(name)) schemeInputs[scheme][name] = value;
      }
    }
  }
}
// The scheme-dependent inputs are colours (currently scrollbar thumbs). Keep
// them responsive to local schemes, including a preset on a dark document root.
for (const name of inputs) {
  const light = schemeInputs.light[name] ?? defaults[name];
  const dark = schemeInputs.dark[name] ?? defaults[name];
  if (light && dark && light !== dark) defaults[name] = `light-dark(${light}, ${dark})`;
}
const mobile = Object.fromEntries(
  [...readFileSync(new URL('mobile.css', directory), 'utf8')
    .matchAll(/^\s*(--coar-[\w-]+):\s*([^;]+);/gm)]
    .map(([, name, value]) => [name, value.trim()]),
);
const output = `// Generated by scripts/write-role-input-defaults.mjs; do not edit.
export const ROLE_INPUT_DEFAULTS: Record<string, string> = ${JSON.stringify(
  Object.fromEntries(Object.entries(defaults).sort(([a], [b]) => a.localeCompare(b))), null, 2,
)};
export const ROLE_MOBILE_DEFAULTS: Record<string, string> = ${JSON.stringify(mobile, null, 2)};
export const ROLE_SCHEME_DEFAULTS: Record<'light' | 'dark', Record<string, string>> = ${JSON.stringify(schemeRoles, null, 2)};
export const ROLE_ROOT_DEFAULTS: Record<string, string> = ${JSON.stringify(rootRoles, null, 2)};
`;
const target = new URL('../src/theme/role-input-defaults.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) {
    console.error('role-input-defaults.ts is stale; run write-role-input-defaults.mjs.');
    process.exit(1);
  }
} else {
  writeFileSync(target, output);
}
